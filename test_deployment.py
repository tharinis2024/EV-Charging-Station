def test_database_selection():
    print('7. Database backend selection...')
    env = os.environ.copy()
    env.pop('DATABASE_URL', None)
    code = ('import sys; sys.path.insert(0, r"%s"); '
            'import database.db as d; '
            'print(int(d.is_postgres()))' % ROOT)
    out = subprocess.run([sys.executable, '-c', code], capture_output=True, text=True, env=env)
    check('SQLite used when DATABASE_URL is unset', out.stdout.strip() == '0', out.stderr)

    env['DATABASE_URL'] = 'postgres://user:pw@host/db'
    out = subprocess.run([sys.executable, '-c', code], capture_output=True, text=True, env=env)
    check('PostgreSQL used when DATABASE_URL is set', out.stdout.strip() == '1', out.stderr)


def test_migrate_cli():
    print('8. migrate.py CLI...')
    env = os.environ.copy()
    env.pop('DATABASE_URL', None)
    out = subprocess.run([sys.executable, os.path.join(ROOT, 'migrate.py'), '--dry-run'],
                         capture_output=True, text=True, env=env, cwd=ROOT)
    check('migrate.py without DATABASE_URL exits 1 with guidance',
          out.returncode == 1 and 'DATABASE_URL' in out.stdout, out.stdout)

    env['DATABASE_URL'] = 'postgres://user:pw@fake-host.invalid/db'
    out = subprocess.run([sys.executable, os.path.join(ROOT, 'migrate.py'), '--dry-run',
                          '--copy-from-sqlite'],
                         capture_output=True, text=True, env=env, cwd=ROOT)
    check('migrate.py --dry-run validates URL, masks password, prints the plan',
          out.returncode == 0 and 'DRY-RUN' in out.stdout and 'user:****@' in out.stdout,
          out.stdout + out.stderr)
    check('dry-run mentions the read-only copy', 'read-only' in out.stdout, out.stdout)


def test_route_sql_portability():
    print('9. Route SQL portability...')
    pattern = re.compile(r'=\\s*\\"(CANCELLED|CONFIRMED|CHARGING|COMPLETED|SUCCESS|FAILED|PENDING)\\"')
    for filename in ('routes/api.py', 'routes/admin_api.py'):
        with open(os.path.join(ROOT, filename), encoding='utf-8') as f:
            source = f.read()
        bad = pattern.findall(source)
        check(f'{filename} has no double-quoted SQL status literals', not bad, bad)


