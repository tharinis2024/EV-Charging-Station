"""
Deployment preparation tests (no network, no hosted database required).

Covers: the SQLite->PostgreSQL placeholder translator, row compatibility,
DATABASE_URL normalization, the PostgreSQL schema's safety properties,
Vercel configuration files, static asset locations, and app importability.

Run:  python test_deployment.py
"""
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)

from database.db import (PgRow, is_postgres, normalize_database_url,
                         translate_query)


def check(name, condition, extra=''):
    assert condition, f'{name} FAILED {extra}'
    print(f'PASS - {name}')


def test_translator():
    print('1. Placeholder translator...')
    check('simple ? translation',
          translate_query('SELECT * FROM users WHERE id = ?') ==
          'SELECT * FROM users WHERE id = %s')
    check('multiple ? placeholders',
          translate_query('UPDATE t SET a = ?, b = ? WHERE c = ?') ==
          'UPDATE t SET a = %s, b = %s WHERE c = %s')
    check('LIKE percent signs are doubled',
          translate_query("SELECT * FROM users WHERE email LIKE '%x%'") ==
          "SELECT * FROM users WHERE email LIKE '%%x%%'")
    check('? inside a string literal stays literal',
          translate_query("SELECT '?' AS q WHERE a = ?") ==
          "SELECT '?' AS q WHERE a = %s")
    check("escaped '' quotes handled",
          translate_query("SELECT * FROM t WHERE name = 'O''Brien' AND id = ?") ==
          "SELECT * FROM t WHERE name = 'O''Brien' AND id = %s")
    check('percent inside literal doubled (legacy password scan)',
          translate_query("SELECT id FROM users WHERE password NOT LIKE 'pbkdf2:%'") ==
          "SELECT id FROM users WHERE password NOT LIKE 'pbkdf2:%%'")
    check('quoted identifier preserved',
          translate_query('SELECT "col%name" FROM t WHERE id = ?') ==
          'SELECT "col%%name" FROM t WHERE id = %s')
    check('no-op when no placeholders or percents',
          translate_query('SELECT COUNT(*) FROM stations') ==
          'SELECT COUNT(*) FROM stations')


def test_pg_row():
    print('2. PostgreSQL row compatibility...')
    description = (('id',), ('name',), ('email',))
    row = PgRow(description, (1, 'Ada', 'ada@example.com'))
    check('row["name"] access', row['name'] == 'Ada')
    check('row[0] integer access', row[0] == 1)
    check('row[-1] negative index', row[-1] == 'ada@example.com')
    check('dict(row) works', dict(row) == {'id': 1, 'name': 'Ada', 'email': 'ada@example.com'})
    check('iteration yields values', list(row) == [1, 'Ada', 'ada@example.com'])
    check('len(row)', len(row) == 3)
    check('keys()', row.keys() == ['id', 'name', 'email'])


def test_url_normalization():
    print('3. DATABASE_URL normalization...')
    check('postgres:// upgraded to postgresql://',
          normalize_database_url('postgres://user:pw@host/db').startswith('postgresql://'))
    check('sslmode appended by default',
          'sslmode=require' in normalize_database_url('postgresql://user:pw@host/db'))
    check('existing sslmode preserved',
          normalize_database_url('postgresql://user:pw@host/db?sslmode=verify-full') ==
          'postgresql://user:pw@host/db?sslmode=verify-full')
    check('appended sslmode uses & when query string exists',
          normalize_database_url('postgresql://user:pw@host/db?channel_binding=require').endswith(
              '&sslmode=require'))


def test_postgres_schema():
    print('4. PostgreSQL schema safety...')
    with open(os.path.join(ROOT, 'database', 'schema_postgres.sql'), encoding='utf-8') as f:
        schema = f.read()
    for table in ('users', 'stations', 'charging_points', 'slots', 'bookings',
                  'payments', 'charging_sessions', 'notifications'):
        check(f'schema defines {table}', f'CREATE TABLE IF NOT EXISTS {table}' in schema)
    check('no SQLite-only AUTOINCREMENT', 'AUTOINCREMENT' not in schema)
    check('no INSERT OR IGNORE (uses ON CONFLICT)', 'OR IGNORE' not in schema and
          schema.count('ON CONFLICT DO NOTHING') >= 4)
    check('booleans use BOOLEAN DEFAULT FALSE', 'BOOLEAN DEFAULT FALSE' in schema and
          'BOOLEAN DEFAULT 0' not in schema)
    check('identity primary keys', 'GENERATED BY DEFAULT AS IDENTITY' in schema)
    check('all CREATE TABLE statements idempotent',
          not re.search(r'^CREATE TABLE (?!IF NOT EXISTS)', schema, re.M))


def test_vercel_config():
    print('5. Vercel configuration...')
    with open(os.path.join(ROOT, 'vercel.json'), encoding='utf-8') as f:
        vercel = json.load(f)
    check('vercel.json targets the app.py entrypoint', 'app.py' in vercel.get('functions', {}))
    check('vercel.json excludes tests/logs from the bundle',
          'test_' in vercel['functions']['app.py'].get('excludeFiles', ''))
    with open(os.path.join(ROOT, '.python-version'), encoding='utf-8') as f:
        check('.python-version pins 3.12', f.read().strip() == '3.12')
    with open(os.path.join(ROOT, 'requirements.txt'), encoding='utf-8') as f:
        reqs = f.read()
    check('requirements pin Flask', 'Flask==' in reqs)
    check('requirements include psycopg2-binary with a <3.14 marker',
          'psycopg2-binary' in reqs and 'python_version < "3.14"' in reqs)
    with open(os.path.join(ROOT, '.gitignore'), encoding='utf-8') as f:
        ignores = f.read().splitlines()
    for pattern in ('.env', '*.db', '.vercel/', 'venv/', '__pycache__/', '*.log'):
        check(f'.gitignore covers {pattern}', pattern in ignores)


